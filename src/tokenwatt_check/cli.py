"""tokenwatt-check: is the GPU you rented performing like it should?"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import sys
import time
from pathlib import Path

from . import __version__, gpu, host, load
from .demo import DEMOS
from .verdict import evaluate, findings_json

ICON = {"PASS": "✅", "WARN": "⚠️ ", "FAIL": "❌", "INFO": "ℹ️ "}


def say(msg: str = "") -> None:
    print(msg, flush=True)


def run_checks(a) -> dict:
    if not gpu.available():
        sys.exit("nvidia-smi not found. tokenwatt-check currently supports NVIDIA GPUs (AMD support is planned).")
    inv_all = gpu.inventory()
    if a.gpu >= len(inv_all):
        sys.exit(f"GPU {a.gpu} not found ({len(inv_all)} visible)")
    inv = inv_all[a.gpu]
    say(f"GPU {a.gpu}: {inv.get('name')} · driver {inv.get('driver_version')} · {inv.get('memory.total')} MiB")
    loadres: dict = {}
    ok, why = load.torch_available()
    if a.no_load:
        loadres["skipped"] = "--no-load"
    elif not ok:
        loadres["skipped"] = why
        say(f"load test skipped: {why}")
    else:
        sampler = gpu.Sampler(gpu=a.gpu).start()
        try:
            say(f"load test: BF16 matmul for {a.seconds:.0f} s ({why}) …")
            mm = load.matmul_tflops(seconds=a.seconds, device=a.gpu)
            say(f"load test: memory copy for {a.seconds / 2:.0f} s …")
            cp = load.copy_bandwidth(seconds=a.seconds / 2, device=a.gpu)
        finally:
            samples = sampler.stop()
        # skip the first few seconds of each phase while clocks settle
        mm["telemetry"] = gpu.summarize(samples, mm["t_start"] + 3, mm["t_end"])
        cp["telemetry"] = gpu.summarize(samples, cp["t_start"] + 2, cp["t_end"])
        loadres = {"matmul": mm, "copy": cp}
    disk = {"skipped": "--no-disk"} if a.no_disk else (say("disk: 2 GB write/read …") or host.disk(a.disk_path))
    net = {"skipped": "--no-net"} if a.no_net else (say("download: 20 s from huggingface.co …") or host.download())
    return {"inventory": inv, "gpus_visible": len(inv_all), "load": loadres, "disk": disk, "download": net}


def render(result: dict) -> str:
    inv, overall, findings, m = result["inventory"], result["overall"], result["findings"], result["metrics"]
    lines = ["", f"tokenwatt-check {result['version']} · {result['time']}",
             f"{inv.get('name')} · driver {inv.get('driver_version')} · {result['host'].get('hostname', '')}", "",
             f"  OVERALL: {ICON[overall]} {overall}", ""]
    for x in findings:
        lines.append(f"  {ICON[x['level']]} {x['check']:<22} {x['message']}")
        if x["advice"]:
            lines.append(f"     {'':<22} → {x['advice']}")
    if m:
        lines += ["", "  " + " · ".join(f"{k}={v}" for k, v in m.items())]
    if result.get("demo"):
        lines += ["", f"  (demo: {result['demo']})"]
    lines += ["", "  Method and reference values: https://www.tokenwatt.io/methodology.html", ""]
    return "\n".join(lines)


def markdown(result: dict) -> str:
    inv = result["inventory"]
    rows = "\n".join(f"| {ICON[x['level']].strip()} {x['level']} | {x['check']} | {x['message']} | {x['advice']} |" for x in result["findings"])
    return (f"# tokenwatt-check report\n\n**{inv.get('name')}** · driver {inv.get('driver_version')} · {result['time']}\n\n"
            f"**Overall: {result['overall']}**\n\n| Result | Check | Finding | What to do |\n|---|---|---|---|\n{rows}\n\n"
            f"Generated by [tokenwatt-check](https://www.tokenwatt.io) {result['version']}.\n")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="tokenwatt-check", description=__doc__)
    ap.add_argument("--version", action="version", version=f"tokenwatt-check {__version__}")
    ap.add_argument("--gpu", type=int, default=0, help="GPU index (default 0)")
    ap.add_argument("--seconds", type=float, default=30, help="matmul load duration; copy test runs half as long")
    ap.add_argument("--no-load", action="store_true", help="skip the GPU load test")
    ap.add_argument("--no-disk", action="store_true")
    ap.add_argument("--no-net", action="store_true")
    ap.add_argument("--disk-path", default=".", help="where to write the temporary disk-test file")
    ap.add_argument("--json", help="write the full result to this file")
    ap.add_argument("--md", help="write a Markdown report to this file")
    ap.add_argument("--demo", choices=sorted(DEMOS), help="show an example report without a GPU")
    a = ap.parse_args(argv)

    t0 = time.time()
    raw = DEMOS[a.demo] if a.demo else run_checks(a)
    overall, findings, metrics = evaluate(raw["inventory"], raw.get("load", {}), raw.get("disk", {}), raw.get("download", {}))
    result = {"tool": "tokenwatt-check", "version": __version__,
              "time": dt.datetime.now(dt.timezone.utc).replace(microsecond=0).isoformat(),
              "host": raw.get("host") or host.info(), **raw, "overall": overall,
              "findings": findings_json(findings), "metrics": metrics, "elapsed_s": round(time.time() - t0, 1)}
    if a.demo:
        result["demo"] = raw.get("note", a.demo)
    say(render(result))
    stamp = dt.datetime.now().strftime("%Y%m%d-%H%M%S")
    jpath = Path(a.json or f"tokenwatt-check-{stamp}.json")
    jpath.write_text(json.dumps(result, indent=2, default=str))
    if a.md:
        Path(a.md).write_text(markdown(result))
    say(f"  full result: {jpath}")
    return {"PASS": 0, "WARN": 0, "FAIL": 2}[overall]


if __name__ == "__main__":
    sys.exit(main())
